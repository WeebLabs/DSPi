#!/usr/bin/env python3
"""Embed an AC-3 vector as a C header for the on-device decode bench.

Reads whole sync frames from the .ac3 file and the expected decode checksum
from the sidecar `<file>.sum` (written by run.sh from ac3_test's output), so
the device can confirm it decodes the same bits as the host.

Usage: gen_bench_frames.py <vector.ac3> <out.h> [--frames N]
"""

import argparse
import sys
from pathlib import Path

RATES = [32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 384, 448, 512, 576, 640]


def frame_len(b, pos):
    """Length of the sync frame at pos, or 0.  Mirrors a52_syncinfo()."""
    if b[pos] != 0x0B or b[pos + 1] != 0x77 or b[pos + 5] >= 0x60:
        return 0
    frmsizecod = b[pos + 4] & 63
    if frmsizecod >= 38:
        return 0
    bitrate = RATES[frmsizecod >> 1]
    fscod = b[pos + 4] & 0xC0
    if fscod == 0:
        return 4 * bitrate
    if fscod == 0x40:
        return 2 * (320 * bitrate // 147 + (frmsizecod & 1))
    if fscod == 0x80:
        return 6 * bitrate
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("vector")
    ap.add_argument("out")
    ap.add_argument("--frames", type=int, default=0, help="0 = all")
    a = ap.parse_args()

    data = Path(a.vector).read_bytes()
    sidecar = Path(a.vector + ".sum")
    checksum = int(sidecar.read_text().split()[0], 16) if sidecar.exists() else 0

    frames = []
    pos = 0
    while pos + 7 <= len(data) and (a.frames == 0 or len(frames) < a.frames):
        n = frame_len(data, pos)
        if n == 0:
            pos += 1
            continue
        if pos + n > len(data):
            break
        frames.append(data[pos:pos + n])
        pos += n
    if not frames:
        print("no frames found", file=sys.stderr)
        return 1

    blob = b"".join(frames)
    lines = ["/* Generated by tools/ac3_test/gen_bench_frames.py from %s; do not edit. */" % Path(a.vector).name,
             "#ifndef AC3_BENCH_FRAMES_H", "#define AC3_BENCH_FRAMES_H", "#include <stdint.h>",
             "#define AC3_BENCH_FRAME_COUNT %d" % len(frames),
             "#define AC3_BENCH_FRAMES_BYTES %d" % len(blob),
             "#define AC3_BENCH_CHECKSUM 0x%08xu" % checksum,
             "static const uint16_t ac3_bench_frame_len[%d] = {%s};" % (len(frames), ", ".join(str(len(f)) for f in frames)),
             "static const uint8_t ac3_bench_frames[%d] = {" % len(blob)]
    for i in range(0, len(blob), 16):
        lines.append("    " + ",".join("0x%02x" % c for c in blob[i:i + 16]) + ",")
    lines += ["};", "#endif /* AC3_BENCH_FRAMES_H */", ""]
    Path(a.out).write_text("\n".join(lines))
    print("wrote %s: %d frames, %d bytes, checksum 0x%08x" % (a.out, len(frames), len(blob), checksum))
    return 0


if __name__ == "__main__":
    sys.exit(main())
