#!/usr/bin/env python3
"""Generate firmware/DSPi/ac3/imdct_tables.h from liba52's a52_imdct_init()
formulas (Kaiser-Bessel derived window, IFFT roots, IMDCT twiddles).

Const tables keep ~3.4 KB out of RAM and make the device decode bit-exact
with the host harness, which checks these values against a C recomputation.

Usage: gen_imdct_tables.py [output path]
"""

import math
import struct
import sys
from pathlib import Path

FFTORDER = [
      0,128, 64,192, 32,160,224, 96, 16,144, 80,208,240,112, 48,176,
      8,136, 72,200, 40,168,232,104,248,120, 56,184, 24,152,216, 88,
      4,132, 68,196, 36,164,228,100, 20,148, 84,212,244,116, 52,180,
    252,124, 60,188, 28,156,220, 92, 12,140, 76,204,236,108, 44,172,
      2,130, 66,194, 34,162,226, 98, 18,146, 82,210,242,114, 50,178,
     10,138, 74,202, 42,170,234,106,250,122, 58,186, 26,154,218, 90,
    254,126, 62,190, 30,158,222, 94, 14,142, 78,206,238,110, 46,174,
      6,134, 70,198, 38,166,230,102,246,118, 54,182, 22,150,214, 86,
]


def bessel_i0(x):
    # Same 100-term recurrence as liba52, so the double result matches.
    b = 1.0
    i = 100
    while i:
        b = b * x / (i * i) + 1
        i -= 1
    return b


def f32(x):
    """Round a double to the nearest float, as the C cast does."""
    return struct.unpack("f", struct.pack("f", x))[0]


def c_float(x):
    # Nine significant digits round-trip any float32; the exponent form
    # keeps a valid float literal for exact integers such as 1.
    return "%.9ef" % x


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else \
        Path(__file__).resolve().parents[2] / "firmware" / "DSPi" / "ac3" / "imdct_tables.h"

    window = []
    s = 0.0
    local = []
    for i in range(256):
        s += bessel_i0(i * (256 - i) * (5 * math.pi / 256) * (5 * math.pi / 256))
        local.append(s)
    s += 1
    for i in range(256):
        window.append(f32(math.sqrt(local[i] / s)))

    roots16 = [f32(math.cos((math.pi / 8) * (i + 1))) for i in range(3)]
    roots32 = [f32(math.cos((math.pi / 16) * (i + 1))) for i in range(7)]
    roots64 = [f32(math.cos((math.pi / 32) * (i + 1))) for i in range(15)]
    roots128 = [f32(math.cos((math.pi / 64) * (i + 1))) for i in range(31)]

    pre1 = []
    for i in range(64):
        k = FFTORDER[i] // 2 + 64
        pre1.append((f32(math.cos((math.pi / 256) * (k - 0.25))),
                     f32(math.sin((math.pi / 256) * (k - 0.25)))))
    for i in range(64, 128):
        k = FFTORDER[i] // 2 + 64
        pre1.append((f32(-math.cos((math.pi / 256) * (k - 0.25))),
                     f32(-math.sin((math.pi / 256) * (k - 0.25)))))
    post1 = [(f32(math.cos((math.pi / 256) * (i + 0.5))),
              f32(math.sin((math.pi / 256) * (i + 0.5)))) for i in range(64)]
    pre2 = []
    for i in range(64):
        k = FFTORDER[i] // 4
        pre2.append((f32(math.cos((math.pi / 128) * (k - 0.25))),
                     f32(math.sin((math.pi / 128) * (k - 0.25)))))
    post2 = [(f32(math.cos((math.pi / 128) * (i + 0.5))),
              f32(math.sin((math.pi / 128) * (i + 0.5)))) for i in range(32)]

    def arr(name, vals, per=4):
        lines = ["static const sample_t %s[%d] = {" % (name, len(vals))]
        for i in range(0, len(vals), per):
            lines.append("    " + ", ".join(c_float(v) for v in vals[i:i + per]) + ",")
        lines.append("};")
        return "\n".join(lines)

    def carr(name, vals, per=2):
        lines = ["static const complex_t %s[%d] = {" % (name, len(vals))]
        for i in range(0, len(vals), per):
            lines.append("    " + ", ".join("{%s, %s}" % (c_float(r), c_float(im))
                                             for r, im in vals[i:i + per]) + ",")
        lines.append("};")
        return "\n".join(lines)

    def barr(name, vals, per=16):
        lines = ["static const uint8_t %s[%d] = {" % (name, len(vals))]
        for i in range(0, len(vals), per):
            lines.append("    " + ",".join("%3d" % v for v in vals[i:i + per]) + ",")
        lines.append("};")
        return "\n".join(lines)

    body = "\n\n".join([
        "/* Generated by tools/ac3_test/gen_imdct_tables.py; do not edit. */",
        "#ifndef IMDCT_TABLES_H\n#define IMDCT_TABLES_H",
        barr("fftorder", FFTORDER),
        arr("roots16", roots16), arr("roots32", roots32),
        arr("roots64", roots64), arr("roots128", roots128),
        carr("pre1", pre1), carr("post1", post1),
        carr("pre2", pre2), carr("post2", post2),
        arr("a52_imdct_window", window),
        "#endif /* IMDCT_TABLES_H */",
    ]) + "\n"
    out.write_text(body)
    print("wrote", out)


if __name__ == "__main__":
    main()
